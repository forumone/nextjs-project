// Generates source/01-global/icon/manifest.ts from the SVGs in
// source/01-global/icon/svgs, so Icon can look up each icon's viewBox
// by name instead of callers hardcoding it.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const svgsDir = path.join(
  import.meta.dirname,
  '..',
  'source/01-global/icon/svgs',
);
const manifestPath = path.join(
  import.meta.dirname,
  '..',
  'source/01-global/icon/manifest.ts',
);

async function getViewBox(filePath) {
  const contents = await readFile(filePath, 'utf8');
  const match = contents.match(/viewBox=["']([^"']+)["']/i);
  if (!match) {
    throw new Error(`No viewBox found in ${filePath}`);
  }
  return match[1];
}

async function generateManifest() {
  const filenames = (await readdir(svgsDir))
    .filter(filename => filename.endsWith('.svg'))
    .sort();

  const entries = await Promise.all(
    filenames.map(async filename => {
      const name = path.basename(filename, '.svg');
      const viewBox = await getViewBox(path.join(svgsDir, filename));
      return [name, viewBox];
    }),
  );

  const identifierPattern = /^[A-Za-z_$][\w$]*$/;
  const entryLines = entries
    .map(([name, viewBox]) => {
      const key = identifierPattern.test(name) ? name : `'${name}'`;
      return `  ${key}: '${viewBox}',`;
    })
    .join('\n');

  const contents = `// This file is automatically generated by lib/generate-icon-manifest.mjs.
// SVGs should be added to icon/svgs. Run \`npm run build-icons\` to regenerate.

const iconManifest = {
${entryLines}
} as const;

export type IconName = keyof typeof iconManifest;

export default iconManifest;
`;

  await writeFile(manifestPath, contents);
  console.log(`Wrote ${entries.length} icons to ${manifestPath}`);
}

generateManifest();
