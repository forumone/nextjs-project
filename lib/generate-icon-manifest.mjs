// Generates source/01-global/icon/manifest.ts from the SVGs in
// source/01-global/icon/svgs, so Icon can look up each icon's viewBox
// by name instead of callers hardcoding it.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const svgsDir = path.join(
  import.meta.dirname,
  '..',
  'source/01-global/icon/svgs',
);
const manifestPath = path.join(
  import.meta.dirname,
  '..',
  'source/01-global/icon/manifest.ts',
);
const force = process.argv.includes('--force');

async function getViewBox(filePath) {
  const contents = await readFile(filePath, 'utf8');
  const match = contents.match(/viewBox=["']([^"']+)["']/i);
  if (!match) {
    throw new Error(`No viewBox found in ${filePath}`);
  }
  return match[1];
}

async function readExistingNames() {
  let contents;
  try {
    contents = await readFile(manifestPath, 'utf8');
  } catch {
    return null;
  }

  const bodyMatch = contents.match(
    /const iconManifest = \{([\s\S]*?)\} as const;/,
  );
  if (!bodyMatch) {
    return null;
  }

  const keyPattern = /^\s*(?:'([^']+)'|([A-Za-z_$][\w$]*)):/gm;
  const names = new Set();
  for (const match of bodyMatch[1].matchAll(keyPattern)) {
    names.add(match[1] ?? match[2]);
  }
  return names;
}

async function isManifestStale(filenames) {
  const existingNames = await readExistingNames();
  if (!existingNames) {
    return true;
  }

  const currentNames = filenames.map(filename =>
    path.basename(filename, '.svg'),
  );
  // Catches added or removed svgs; a shared count with every current name
  // already present means nothing to add or remove.
  if (currentNames.length !== existingNames.size) {
    return true;
  }

  return currentNames.some(name => !existingNames.has(name));
}

async function generateManifest() {
  const filenames = (await readdir(svgsDir))
    .filter(filename => filename.endsWith('.svg'))
    .sort();

  if (!force && !(await isManifestStale(filenames))) {
    console.log('✅ Icon manifest is up to date, skipping regeneration.');
    return;
  }

  const entries = await Promise.all(
    filenames.map(async filename => {
      const name = path.basename(filename, '.svg');
      const viewBox = await getViewBox(path.join(svgsDir, filename));
      return [name, viewBox];
    }),
  );

  const identifierPattern = /^[A-Za-z_$][\w$]*$/;
  const entryLines = entries
    .map(([name, viewBox]) => {
      const key = identifierPattern.test(name) ? name : `'${name}'`;
      return `  ${key}: '${viewBox}',`;
    })
    .join('\n');

  const contents = `// This file is automatically generated by lib/generate-icon-manifest.mjs.
// SVGs should be added to icon/svgs. Run \`npm run build-icons\` to regenerate,
// or restart the server. If you edited an existing SVG in place, run
// \`npm run build-icons:force\` instead, since the name-based staleness check
// won't notice a same-named file changed.

const iconManifest = {
${entryLines}
} as const;

export type IconName = keyof typeof iconManifest;

export default iconManifest;
`;

  await writeFile(manifestPath, contents);
  console.log(`📝 Wrote ${entries.length} icons to ${manifestPath}`);
}

generateManifest();
